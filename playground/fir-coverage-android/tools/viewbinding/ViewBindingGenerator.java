import java.io.FileOutputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.zip.ZipEntry;
import java.util.zip.ZipOutputStream;
import javax.xml.parsers.DocumentBuilderFactory;
import org.w3c.dom.Element;
import org.w3c.dom.Node;

/**
 * Writes view binding classes for Android layouts into a srcjar, the way
 * AGP's {@code viewBinding = true} does: {@code activity_main.xml} becomes
 * {@code <package>.databinding.ActivityMainBinding} with a field per view id
 * and {@code inflate}/{@code bind} factories.
 *
 * <p>Usage: ViewBindingGenerator PACKAGE OUT.srcjar LAYOUT.xml...
 *
 * <p>Covers what the sample uses: plain views with {@code @+id/} ids. No
 * includes, merges, or configuration-specific layouts.
 */
public final class ViewBindingGenerator {
    private static final String ANDROID_NS = "http://schemas.android.com/apk/res/android";

    private record BoundView(String field, String id, String type) {}

    public static void main(String[] args) throws Exception {
        if (args.length < 3) {
            throw new IllegalArgumentException("usage: ViewBindingGenerator PACKAGE OUT.srcjar LAYOUT.xml...");
        }
        String pkg = args[0];
        try (ZipOutputStream zip = new ZipOutputStream(new FileOutputStream(args[1]))) {
            for (int i = 2; i < args.length; i++) {
                Path layout = Path.of(args[i]);
                String layoutName = layout.getFileName().toString().replaceFirst("\\.xml$", "");
                String className = camel(layoutName, true) + "Binding";
                String source = generate(pkg, layoutName, className, layout);
                ZipEntry entry = new ZipEntry(pkg.replace('.', '/') + "/databinding/" + className + ".java");
                entry.setTime(0); // reproducible srcjar
                zip.putNextEntry(entry);
                zip.write(source.getBytes(StandardCharsets.UTF_8));
                zip.closeEntry();
            }
        }
    }

    private static String generate(String pkg, String layoutName, String className, Path layout)
            throws Exception {
        DocumentBuilderFactory factory = DocumentBuilderFactory.newInstance();
        factory.setNamespaceAware(true);
        factory.setFeature("http://apache.org/xml/features/disallow-doctype-decl", true);
        factory.setXIncludeAware(false);
        factory.setExpandEntityReferences(false);
        Element root = factory.newDocumentBuilder().parse(layout.toFile()).getDocumentElement();
        String rootType = viewType(root.getTagName());
        List<BoundView> views = new ArrayList<>();
        collect(root, views, true);

        StringBuilder out = new StringBuilder();
        out.append("// Generated by tools/viewbinding from ").append(layoutName).append(".xml. Do not edit.\n");
        out.append("package ").append(pkg).append(".databinding;\n\n");
        out.append("import android.view.LayoutInflater;\n");
        out.append("import android.view.View;\n");
        out.append("import android.view.ViewGroup;\n");
        out.append("import ").append(pkg).append(".R;\n\n");
        out.append("public final class ").append(className).append(" {\n");
        out.append("  private final ").append(rootType).append(" rootView;\n");
        for (BoundView view : views) {
            out.append("  public final ").append(view.type()).append(' ').append(view.field()).append(";\n");
        }
        out.append("\n  private ").append(className).append('(').append(rootType).append(" rootView");
        for (BoundView view : views) {
            out.append(", ").append(view.type()).append(' ').append(view.field());
        }
        out.append(") {\n    this.rootView = rootView;\n");
        for (BoundView view : views) {
            out.append("    this.").append(view.field()).append(" = ").append(view.field()).append(";\n");
        }
        out.append("  }\n\n");
        out.append("  public ").append(rootType).append(" getRoot() {\n    return rootView;\n  }\n\n");
        out.append("  public static ").append(className).append(" inflate(LayoutInflater inflater) {\n");
        out.append("    return inflate(inflater, null, false);\n  }\n\n");
        out.append("  public static ").append(className)
                .append(" inflate(LayoutInflater inflater, ViewGroup parent, boolean attachToParent) {\n");
        out.append("    View root = inflater.inflate(R.layout.").append(layoutName).append(", parent, false);\n");
        out.append("    if (attachToParent) {\n      parent.addView(root);\n    }\n");
        out.append("    return bind(root);\n  }\n\n");
        out.append("  public static ").append(className).append(" bind(View rootView) {\n");
        for (BoundView view : views) {
            out.append("    ").append(view.type()).append(' ').append(view.field())
                    .append(" = rootView.findViewById(R.id.").append(view.id()).append(");\n");
            out.append("    if (").append(view.field()).append(" == null) {\n");
            out.append("      throw new NullPointerException(\"Missing required view with ID: ")
                    .append(view.id()).append("\");\n    }\n");
        }
        out.append("    return new ").append(className).append("((").append(rootType).append(") rootView");
        for (BoundView view : views) {
            out.append(", ").append(view.field());
        }
        out.append(");\n  }\n}\n");
        return out.toString();
    }

    private static void collect(Element element, List<BoundView> views, boolean isRoot) {
        String id = element.getAttributeNS(ANDROID_NS, "id");
        if (!isRoot && id.startsWith("@+id/")) {
            String name = id.substring("@+id/".length());
            views.add(new BoundView(camel(name, false), name, viewType(element.getTagName())));
        }
        for (Node child = element.getFirstChild(); child != null; child = child.getNextSibling()) {
            if (child instanceof Element childElement) {
                collect(childElement, views, false);
            }
        }
    }

    private static String viewType(String tag) {
        if (tag.contains(".")) {
            return tag;
        }
        return switch (tag) {
            case "View", "ViewStub", "SurfaceView", "TextureView" -> "android.view." + tag;
            case "WebView" -> "android.webkit.WebView";
            default -> "android.widget." + tag;
        };
    }

    private static String camel(String snake, boolean upperFirst) {
        StringBuilder out = new StringBuilder();
        boolean upper = upperFirst;
        for (char c : snake.toCharArray()) {
            if (c == '_') {
                upper = true;
            } else {
                out.append(upper ? Character.toUpperCase(c) : c);
                upper = false;
            }
        }
        return out.toString();
    }

    private ViewBindingGenerator() {}
}
