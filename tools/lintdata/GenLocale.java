import com.android.ide.common.resources.LocaleManager;
import java.util.*;

/** Dumps Android Lint's LocaleManager tables as a Go source file. See regen-locale.sh. */
public class GenLocale {
  static String q(String s) { return "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\""; }

  public static void main(String[] args) {
    StringBuilder sb = new StringBuilder();
    sb.append("// Code generated by tools/lintdata/regen-locale.sh from Android Lint's LocaleManager. DO NOT EDIT.\n\n");
    sb.append("package rules\n\n");
    List<String> langs = new ArrayList<>(LocaleManager.getLanguageCodes(true));
    Collections.sort(langs);
    sb.append("// lintLanguageNames maps a language code to its LocaleManager display name.\n");
    sb.append("var lintLanguageNames = map[string]string{\n");
    for (String l : langs) {
      String n = LocaleManager.getLanguageName(l);
      if (n != null) sb.append("\t" + q(l) + ": " + q(n) + ",\n");
    }
    sb.append("}\n\n");
    List<String> regions = new ArrayList<>(LocaleManager.getRegionCodes(true));
    Collections.sort(regions);
    sb.append("// lintRegionNames maps a region code to its LocaleManager display name.\n");
    sb.append("var lintRegionNames = map[string]string{\n");
    for (String r : regions) {
      String n = LocaleManager.getRegionName(r);
      if (n != null) sb.append("\t" + q(r) + ": " + q(n) + ",\n");
    }
    sb.append("}\n\n");
    sb.append("// lintRelevantRegions maps a language to the regions LocaleManager pairs it with.\n");
    List<String> relevant = new ArrayList<>();
    for (String l : langs) {
      List<String> rr = LocaleManager.getRelevantRegions(l);
      if (rr != null && !rr.isEmpty()) relevant.add(l + "=" + String.join(",", rr));
    }
    sb.append("var lintRelevantRegions = decodeListMap(\n");
    StringBuilder line = new StringBuilder();
    List<String> chunks = new ArrayList<>();
    for (String e : relevant) {
      if (line.length() > 0 && line.length() + e.length() + 1 > 110) {
        chunks.add(line.toString());
        line.setLength(0);
      }
      if (line.length() > 0) line.append(' ');
      line.append(e);
    }
    if (line.length() > 0) chunks.add(line.toString());
    for (int i = 0; i < chunks.size(); i++)
      sb.append("\t\"" + chunks.get(i) + (i < chunks.size() - 1 ? " \" +\n" : "\",\n"));
    sb.append(")\n\n");
    sb.append("// lintDefaultRegion maps a language to its default region.\n");
    sb.append("var lintDefaultRegion = map[string]string{\n");
    for (String l : langs) {
      String d = LocaleManager.getDefaultLanguageRegion(l);
      if (d != null) sb.append("\t" + q(l) + ": " + q(d) + ",\n");
    }
    sb.append("}\n\n");
    sb.append("// lintValidRegions is the set of region codes LocaleManager.isValidRegionCode accepts.\n");
    sb.append("var lintValidRegions = map[string]bool{\n");
    for (char a = 'A'; a <= 'Z'; a++)
      for (char b = 'A'; b <= 'Z'; b++) {
        String c = "" + a + b;
        if (LocaleManager.isValidRegionCode(c)) sb.append("\t" + q(c) + ": true,\n");
      }
    sb.append("}\n\n");
    sb.append("// lintLanguageAlpha2 maps a three-letter language code to its two-letter code.\n");
    sb.append("var lintLanguageAlpha2 = map[string]string{\n");
    for (char a = 'a'; a <= 'z'; a++)
      for (char b = 'a'; b <= 'z'; b++)
        for (char c = 'a'; c <= 'z'; c++) {
          String code = "" + a + b + c;
          String two = LocaleManager.getLanguageAlpha2(code);
          if (two != null) sb.append("\t" + q(code) + ": " + q(two) + ",\n");
        }
    sb.append("}\n\n");
    sb.append("// lintRegionAlpha2 maps a three-letter region code to its two-letter code.\n");
    sb.append("var lintRegionAlpha2 = map[string]string{\n");
    for (char a = 'A'; a <= 'Z'; a++)
      for (char b = 'A'; b <= 'Z'; b++)
        for (char c = 'A'; c <= 'Z'; c++) {
          String code = "" + a + b + c;
          String two = LocaleManager.getRegionAlpha2(code);
          if (two != null) sb.append("\t" + q(code) + ": " + q(two) + ",\n");
        }
    sb.append("}\n");
    System.out.print(sb);
  }
}
