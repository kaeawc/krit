// The gate over the registered rules, TestRulesPackageReadersDeclareBuildInfo, lives in internal/rules, whose test
// binary make lint-rules links anyway: it reads the rules' scopes and check functions from api.Registry.

// fixtureLine is the line of the fixture holding marker.
func fixtureLine(t *testing.T, dir, marker string) int {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(dir, "fixture.go"))
	if err != nil {
		t.Fatal(err)
	}
	for i, line := range strings.Split(string(data), "\n") {
		if strings.Contains(line, marker) {
			return i + 1
		}
	}
	t.Fatalf("no %q in fixture", marker)
	return 0
}

var buildInfoFixture = sync.OnceValues(func() (*typedPackage, error) {
	return loadTypedPackage(filepath.Join("testdata", "buildinforeach"))
})

func analyzeBuildInfoFixture(t *testing.T, roots []BuildInfoRoot, helpers []string) ([]Violation, error) {
	t.Helper()
	prog, err := buildInfoFixture()
	if err != nil {
		t.Fatal(err)
	}
	return analyzeBuildInfoReach(prog, roots, helpers, BuildInfoCovered)
}

func TestAnalyzeBuildInfoReach(t *testing.T) {
	t.Parallel()
	dir := filepath.Join("testdata", "buildinforeach")
	method := func(rule, impl, scope string) BuildInfoRoot {
		return BuildInfoRoot{Rule: rule, Scope: scope, Impl: impl, Funcs: []RuntimeFunc{{Name: "(*" + impl + ").check-fm", File: "<autogenerated>", Line: 1}}}
	}
	res := BuildInfoScopeResource
	closureLine := fixtureLine(t, dir, "closureCheckLine")
	varLine := fixtureLine(t, dir, "var checkFuncVar")
	roots := []BuildInfoRoot{
		method("Direct", "DirectRule", res),
		method("Declared", "DeclaredRule", res),
		method("Transitive", "TransitiveRule", res),
		method("OtherType", "OtherTypeRule", res),
		method("Closure", "ClosureRule", res),
		method("FuncValue", "FuncValueRule", res),
		method("FieldValue", "FieldValueRule", res),
		method("Interface", "InterfaceRule", res),
		method("UnusedReader", "UnusedReaderRule", res),
		method("Plain", "PlainRule", res),
		method("Stringer", "StringerRule", res),
		method("Covered", "CoveredRule", res),
		method("Icon", "IconRule", BuildInfoScopeIcons),
		method("SourceDeclared", "DeclaredRule", BuildInfoScopeResourceSource),
		method("NotGatedScope", "DirectRule", "manifest"),
		{Rule: "PackageFunc", Scope: res, Funcs: []RuntimeFunc{{Name: "checkPackageFunc", File: "fixture.go", Line: 1}}},
		{Rule: "ClosureCheck", Scope: res, Funcs: []RuntimeFunc{{Name: "init.0.func1", File: "/elsewhere/fixture.go", Line: closureLine}}},
		{Rule: "FuncVarCheck", Scope: res, Funcs: []RuntimeFunc{{Name: "glob..func1", File: "fixture.go", Line: varLine}}},
	}
	violations, err := analyzeBuildInfoFixture(t, roots, BuildInfoHelpers)
	if err != nil {
		t.Fatal(err)
	}
	got := map[string]string{}
	for _, v := range violations {
		if _, dup := got[v.RuleID]; dup {
			t.Errorf("rule %s reported twice", v.RuleID)
		}
		got[v.RuleID] = v.Message
		t.Log(v.String())
	}
	const fix = "implement rules.ResourceBuildInfoReader so the build-info fingerprint is in this rule's cache keys"
	const limit = "calls through function values stored elsewhere (fields, parameters, maps) are not followed"
	for rule, want := range map[string][]string{
		"Direct":       {"reaches build-file helper resourceModuleMinSdk ((*DirectRule).check -> resourceModuleMinSdk)", fix, limit},
		"Transitive":   {"resourceModuleMinSdk ((*TransitiveRule).check -> transitiveMinSdk -> resourceModuleMinSdk)", fix},
		"OtherType":    {"((*OtherTypeRule).check -> (moduleFacts).minSdk -> resourceModuleMinSdk)", fix},
		"Closure":      {"resourceModuleMinSdk ((*ClosureRule).check -> resourceModuleMinSdk)", fix},
		"FuncValue":    {"resourceModuleMinSdk ((*FuncValueRule).check -> resourceModuleMinSdk)", fix},
		"Interface":    {"((*InterfaceRule).check -> (minSdkSource).minSdk -> (moduleFacts).minSdk -> resourceModuleMinSdk)", fix},
		"PackageFunc":  {"readModuleIdentity (checkPackageFunc -> readModuleIdentity)", fix},
		"ClosureCheck": {"readModuleVectorSettings (func@fixture.go:", fix},
		"FuncVarCheck": {"gradleModulePath (func@fixture.go:", fix},
		"UnusedReader": {"implements ResourceBuildInfoReader but reaches none of ruleslinter.BuildInfoHelpers", limit},
		"Icon":         {"icons rule reaches build-file helper manifestRoot", "icons cache keys take no build info", limit},
		"SourceDeclared": {
			"resource-source rule reaches build-file helper resourceModuleMinSdk",
			"ResourceBuildInfoReader is only read for resource-scope rules",
		},
	} {
		msg, ok := got[rule]
		if !ok {
			t.Errorf("rule %s: no violation, want one", rule)
			continue
		}
		for _, w := range want {
			if !strings.Contains(msg, w) {
				t.Errorf("rule %s: message %q lacks %q", rule, msg, w)
			}
		}
		delete(got, rule)
	}
	// Declared, Plain, Stringer and Covered are correct; FieldValue is the known limit; NotGatedScope is a manifest
	// rule, which the gate does not check.
	for rule, msg := range got {
		t.Errorf("rule %s: unexpected violation %q", rule, msg)
	}
}

func TestAnalyzeBuildInfoReachRejectsUnresolvedRoots(t *testing.T) {
	t.Parallel()
	for _, f := range []RuntimeFunc{
		{Name: "(*MissingRule).check-fm"},
		{Name: "(*DirectRule).missing-fm"},
		{Name: "missingFunc"},
		{Name: "init.0.func9", File: "fixture.go", Line: 1},
	} {
		_, err := analyzeBuildInfoFixture(t, []BuildInfoRoot{{Rule: "R", Scope: BuildInfoScopeResource, Funcs: []RuntimeFunc{f}}}, BuildInfoHelpers)
		if err == nil || !strings.Contains(err.Error(), "cannot resolve") {
			t.Errorf("%s: err = %v, want cannot resolve", f.Name, err)
		}
	}
}

func TestAnalyzeBuildInfoReachRequiresEveryHelper(t *testing.T) {
	t.Parallel()
	_, err := analyzeBuildInfoFixture(t, nil, append(append([]string(nil), BuildInfoHelpers...), "renamedHelper"))
	if err == nil || !strings.Contains(err.Error(), "renamedHelper") {
		t.Fatalf("err = %v, want one naming renamedHelper", err)
	}
}
