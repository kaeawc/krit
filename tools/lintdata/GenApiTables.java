import com.android.tools.lint.LintCliClient;
import com.android.tools.lint.checks.ApiLookup;
import com.android.tools.lint.client.api.LintClient;
import java.nio.file.Files;
import java.nio.file.Paths;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/** Dumps Android Lint's API database tables as Go source. See regen-api-tables.sh. */
public class GenApiTables {
  static String q(String s) { return "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\""; }

  public static void main(String[] args) throws Exception {
    LintClient.Companion.setClientName("CLI");
    LintCliClient client = new LintCliClient("regen");
    ApiLookup db = ApiLookup.get(client);
    String xml = new String(Files.readAllBytes(Paths.get(args[0])));
    StringBuilder sb = new StringBuilder();
    sb.append("// Code generated by tools/lintdata/regen-api-tables.sh from Android Lint's API database. DO NOT EDIT.\n\n");
    sb.append("package rules\n\n");
    Matcher m = Pattern.compile("<class name=\"android/R\\$attr\"[^>]*>(.*?)</class>", Pattern.DOTALL).matcher(xml);
    if (!m.find()) throw new IllegalStateException("android/R$attr not found in " + args[0]);
    Matcher f = Pattern.compile("<field name=\"([^\"]+)\"").matcher(m.group(1));
    sb.append("// lintAttrSince maps an android.R.attr name to the API level that introduced it, for levels above 1.\n");
    sb.append("var lintAttrSince = map[string]int{\n");
    java.util.TreeMap<String, Integer> sorted = new java.util.TreeMap<>();
    while (f.find()) {
      int v = db.getFieldVersion("android/R$attr", f.group(1));
      if (v > 1) sorted.put(f.group(1), v);
    }
    for (java.util.Map.Entry<String, Integer> e : sorted.entrySet()) sb.append("\t" + q(e.getKey()) + ": " + e.getValue() + ",\n");
    sb.append("}\n");
    System.out.print(sb);
  }
}
