import com.android.tools.lint.checks.SystemPermissionsDetector;
import java.lang.reflect.Field;
import java.lang.reflect.Method;
import java.util.*;

/** Dumps tables from Android Lint's manifest detectors as Go source. See regen-tables.sh. */
public class GenManifestTables {
  static String q(String s) { return "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\""; }

  public static void main(String[] args) throws Exception {
    StringBuilder sb = new StringBuilder();
    sb.append("// Code generated by tools/lintdata/regen-tables.sh from Android Lint's detectors. DO NOT EDIT.\n\n");
    sb.append("package rules\n\n");
    Field f = SystemPermissionsDetector.class.getDeclaredField("SYSTEM_PERMISSIONS");
    f.setAccessible(true);
    String[] perms = (String[]) f.get(null);
    Method m = SystemPermissionsDetector.class.getDeclaredMethod("getLastNonSignatureApiLevel", String.class);
    m.setAccessible(true);
    sb.append("// lintSystemPermissions maps each permission SystemPermissionsDetector reports to the last API level\n");
    sb.append("// at which apps could still hold it, or -1 when it was never grantable to apps.\n");
    sb.append("var lintSystemPermissions = map[string]int{\n");
    for (String p : perms) sb.append("\t" + q(p) + ": " + m.invoke(null, p) + ",\n");
    sb.append("}\n");
    System.out.print(sb);
  }
}
